class PlanError(Exception):
    """An error that should be shown to a CLI user without a traceback."""


def load_messages(language: str) -> dict[str, str]:
    """Validate both bundled catalogs before rendering any output."""
    if language not in ("en", "zh-CN"):
        raise PlanError("language must be en or zh-CN")
    catalogs = {}
    for code in ("en", "zh-CN"):
        try:
            messages = json.loads((LOCALES_DIR / f"{code}.json").read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            raise PlanError(f"Cannot load locale {code}: {exc}") from exc
        if not isinstance(messages, dict) or set(messages) != MESSAGE_KEYS:
            raise PlanError(f"Locale {code} must contain all required message keys")
        if any(not isinstance(value, str) or not value for value in messages.values()):
            raise PlanError(f"Locale {code} contains an invalid message")
        catalogs[code] = messages
    formatter = Formatter()
    for key in MESSAGE_KEYS:
        try:
            fields = [{field for _, field, _, _ in formatter.parse(catalogs[code][key]) if field is not None}
                      for code in ("en", "zh-CN")]
        except ValueError as exc:
            raise PlanError(f"Invalid locale template: {key}") from exc
        if fields[0] != fields[1]:
            raise PlanError(f"Locale placeholders differ: {key}")
    try:
        bundle = localization.get_bundle(language, skill_dir=LOCALES_DIR.parent.parent)
    except localization.LocalizationError as exc:
        raise PlanError(str(exc)) from exc
    return bundle["messages"]


def _display_messages(schedule: dict[str, Any]) -> dict[str, str]:
    bundle = schedule.get("_locale_bundle")
    if bundle is not None:
        try:
            return localization.validate_bundle(bundle, language=schedule["language"])["messages"]
        except localization.LocalizationError as exc:
            raise PlanError(str(exc)) from exc
    # Compatibility for older Chinese/English inputs without a snapshot.
    return load_messages(schedule["language"])


def _public_schedule(schedule: dict[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in schedule.items() if not key.startswith("_")}


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _finite_nonnegative(value: Any) -> bool:
    if not _is_number(value):
        return False
    try:
        return math.isfinite(float(value)) and value >= 0
    except (OverflowError, ValueError):
        return False


def _require_keys(obj: dict[str, Any], keys: tuple[str, ...], where: str, errors: list[str]) -> None:
    for key in keys:
        if key not in obj:
            errors.append(f"{where} 缺少字段 {key!r}")


def _string_list(value: Any, where: str, errors: list[str], *, nonempty: bool = False) -> list[str]:
    if not isinstance(value, list):
        errors.append(f"{where} 必须是字符串数组")
        return []
    result: list[str] = []
    for index, item in enumerate(value):
        if not isinstance(item, str) or (nonempty and not item.strip()):
            errors.append(f"{where}[{index}] 必须是{'非空' if nonempty else ''}字符串")
        else:
            result.append(item)
    if len(result) != len(set(result)):
        errors.append(f"{where} 不允许重复项")
    return result


def validate_plan(raw: Any, *, input_dir: Path | None = None) -> dict[str, Any]:
    """Return a normalized plan, or raise PlanError with all useful validation errors."""
    if not isinstance(raw, dict):
        raise PlanError("输入 JSON 顶层必须是对象")
    errors: list[str] = []
    required = ("version", "title", "summary", "assumptions", "risks", "requirements", "max_parallel", "tasks")
    _require_keys(raw, required, "顶层", errors)

    if type(raw.get("version")) is not int or raw.get("version") != 1:
        errors.append("version 必须严格等于整数 1")
    title = raw.get("title")
    if not isinstance(title, str) or not title.strip():
        errors.append("title 必须是非空字符串")
    if not isinstance(raw.get("summary"), str):
        errors.append("summary 必须是字符串")
    language = raw.get("language", DEFAULT_LANGUAGE)
    try:
        language = localization.normalize_language(language)
    except localization.LocalizationError as exc:
        errors.append(f"language 无效（计划输入不能为 null）: {exc}")
        language = DEFAULT_LANGUAGE
    locale_bundle = None
    locale_reference = raw.get("localization")
    if "localization" in raw:
        try:
            if not isinstance(locale_reference, dict) or set(locale_reference) != {"snapshot", "messages_sha256"}:
                raise PlanError("localization 必须包含 snapshot 和 messages_sha256")
            name = locale_reference["snapshot"]
            if not isinstance(name, str) or not name or "\\" in name:
                raise PlanError("localization snapshot 必须为计划目录中的相对路径")
            relative = Path(name)
            if relative.is_absolute() or ".." in relative.parts or ":" in name:
                raise PlanError("localization snapshot 必须为计划目录中的相对路径")
            if input_dir is None:
                raise PlanError("localization snapshot 需要计划输入目录")
            path = (input_dir / relative).resolve()
            if not path.is_relative_to(input_dir.resolve()):
                raise PlanError("localization snapshot 超出计划输入目录")
            locale_bundle = localization.validate_bundle(
                json.loads(path.read_text(encoding="utf-8")), language=language,
            )
            if locale_reference["messages_sha256"] != locale_bundle["messages_sha256"]:
                raise PlanError("localization messages_sha256 与文案快照不一致")
        except (OSError, ValueError, PlanError) as exc:
            errors.append(f"localization 无效: {exc}")
    elif language not in ("en", "zh-CN"):
        errors.append(f"language {language} 需要通过语义核验的 localization snapshot")
    messages = locale_bundle["messages"] if locale_bundle is not None else load_messages(
        language if language in ("en", "zh-CN") else DEFAULT_LANGUAGE
    )
    unit = raw.get("unit") if "unit" in raw else messages["unit"]
    if not isinstance(unit, str) or not unit.strip():
        errors.append("unit 必须是非空字符串")
    assumptions = _string_list(raw.get("assumptions"), "assumptions", errors)
    risks = _string_list(raw.get("risks"), "risks", errors)

    max_parallel = raw.get("max_parallel")
    if max_parallel is not None and (
        not isinstance(max_parallel, int) or isinstance(max_parallel, bool) or max_parallel <= 0
    ):
        errors.append("max_parallel 必须是正整数或 null（未知）")

    requirements_raw = raw.get("requirements")
    requirements: list[dict[str, str]] = []
    requirement_ids: set[str] = set()
    if not isinstance(requirements_raw, list):
        errors.append("requirements 必须是数组")
    else:
        for index, req in enumerate(requirements_raw):
            where = f"requirements[{index}]"
            if not isinstance(req, dict):
                errors.append(f"{where} 必须是对象")
                continue
            _require_keys(req, ("id", "text", "source"), where, errors)
            req_id = req.get("id")
            if not isinstance(req_id, str) or not req_id.strip():
                errors.append(f"{where}.id 必须是非空字符串")
            elif req_id in requirement_ids:
                errors.append(f"需求 ID 重复: {req_id}")
            else:
                requirement_ids.add(req_id)
            for key in ("text", "source"):
                if not isinstance(req.get(key), str):
                    errors.append(f"{where}.{key} 必须是字符串")
            if isinstance(req_id, str) and isinstance(req.get("text"), str) and isinstance(req.get("source"), str):
                requirements.append({"id": req_id, "text": req["text"], "source": req["source"]})

    tasks_raw = raw.get("tasks")
    tasks: list[dict[str, Any]] = []
    task_ids: set[str] = set()
    task_fields = (
        "id", "title", "description", "requirement_ids", "duration", "depends_on", "resources",
        "deliverable", "acceptance", "estimate_basis", "kind", "external_ready", "pr_scope",
    )
    if not isinstance(tasks_raw, list):
        errors.append("tasks 必须是数组")
    else:
        for index, task in enumerate(tasks_raw):
            where = f"tasks[{index}]"
            if not isinstance(task, dict):
                errors.append(f"{where} 必须是对象")
                continue
            _require_keys(task, task_fields, where, errors)
            task_id = task.get("id")
            if not isinstance(task_id, str) or not task_id.strip():
                errors.append(f"{where}.id 必须是非空字符串")
            elif task_id in task_ids:
                errors.append(f"任务 ID 重复: {task_id}")
            else:
                task_ids.add(task_id)
            for key in ("title", "description", "deliverable", "estimate_basis", "pr_scope"):
                value = task.get(key)
                if not isinstance(value, str) or (key == "title" and not value.strip()):
                    errors.append(f"{where}.{key} 必须是{'非空' if key == 'title' else ''}字符串")
            req_ids = _string_list(task.get("requirement_ids"), f"{where}.requirement_ids", errors, nonempty=True)
            deps = _string_list(task.get("depends_on"), f"{where}.depends_on", errors, nonempty=True)
            resources = _string_list(task.get("resources"), f"{where}.resources", errors, nonempty=True)
            acceptance = _string_list(task.get("acceptance"), f"{where}.acceptance", errors)
            kind = task.get("kind")
            if kind not in ("task", "milestone", "external"):
                errors.append(f"{where}.kind 必须是 task、milestone 或 external")
            duration = task.get("duration")
            if not _finite_nonnegative(duration):
                errors.append(f"{where}.duration 必须是有限非负数")
            elif kind in ("milestone", "external") and duration != 0:
                errors.append(f"{where}.duration 在 milestone 或 external 类型下必须为 0")
            elif kind == "task" and duration == 0:
                errors.append(f"{where}.duration 在 task 类型下必须大于 0")
            external_ready = task.get("external_ready")
            if kind == "external":
                if external_ready is not None and not _finite_nonnegative(external_ready):
                    errors.append(f"{where}.external_ready 必须是有限非负数或 null")
            elif external_ready is not None:
                errors.append(f"{where}.external_ready 仅 external 可设置；其他类型必须为 null")
            if isinstance(task_id, str):
                tasks.append({
                    "id": task_id,
                    "title": task.get("title"),
                    "description": task.get("description"),
                    "requirement_ids": req_ids,
                    "duration": duration,
                    "depends_on": deps,
                    "resources": resources,
                    "deliverable": task.get("deliverable"),
                    "acceptance": acceptance,
                    "estimate_basis": task.get("estimate_basis"),
                    "kind": kind,
                    "external_ready": external_ready,
                    "pr_scope": task.get("pr_scope"),
                })

    for task in tasks:
        for dep in task["depends_on"]:
            if dep not in task_ids:
                errors.append(f"任务 {task['id']} 引用了未知依赖 {dep}")
        for req_id in task["requirement_ids"]:
            if req_id not in requirement_ids:
                errors.append(f"任务 {task['id']} 引用了未知需求 {req_id}")

    covered = {req_id for task in tasks for req_id in task["requirement_ids"]}
    for req_id in sorted(requirement_ids - covered):
        errors.append(f"需求未被任何任务覆盖: {req_id}")

    if not errors and tasks:
        _topological_order(tasks)  # Raises a precise cycle error.
    if errors:
        raise PlanError("输入校验失败：\n- " + "\n- ".join(errors))
    normalized = {
        "version": 1,
        "language": language,
        "title": title,
        "summary": raw["summary"],
        "unit": unit,
        "assumptions": assumptions,
        "risks": risks,
        "requirements": requirements,
        "max_parallel": max_parallel,
        "tasks": tasks,
    }
    if locale_bundle is not None:
        normalized["localization"] = dict(locale_reference)
        normalized["_locale_bundle"] = locale_bundle
    return normalized


def _topological_order(tasks: list[dict[str, Any]]) -> list[str]:
    index = {task["id"]: i for i, task in enumerate(tasks)}
    indegree = {task["id"]: len(task["depends_on"]) for task in tasks}
    children = {task["id"]: [] for task in tasks}
    for task in tasks:
        for dep in task["depends_on"]:
            children[dep].append(task["id"])
    ready = [(index[task_id], task_id) for task_id, degree in indegree.items() if degree == 0]
    heapq.heapify(ready)
    order: list[str] = []
    while ready:
        _, task_id = heapq.heappop(ready)
        order.append(task_id)
        for child in children[task_id]:
            indegree[child] -= 1
            if indegree[child] == 0:
                heapq.heappush(ready, (index[child], child))
    if len(order) != len(tasks):
        remaining = [task["id"] for task in tasks if indegree[task["id"]] > 0]
        raise PlanError("依赖图存在循环，涉及任务: " + ", ".join(remaining))
    return order


def build_schedule(plan: dict[str, Any]) -> dict[str, Any]:
    tasks = plan["tasks"]
    task_map = {task["id"]: task for task in tasks}
    topo = _topological_order(tasks)

    blocked_by: dict[str, set[str]] = {task["id"]: set() for task in tasks}
    for task_id in topo:
        task = task_map[task_id]
        if task["kind"] == "external" and task["external_ready"] is None:
            blocked_by[task_id].add(task_id)
        for dep in task["depends_on"]:
            blocked_by[task_id].update(blocked_by[dep])

    scheduled: dict[str, dict[str, float]] = {}
    pending = [task["id"] for task in tasks if not blocked_by[task["id"]]]
    current = 0.0
    while pending:
        active = lambda: [
            task_map[task_id] for task_id, timing in scheduled.items()
            if task_map[task_id]["kind"] == "task" and timing["start"] <= current
            and timing["finish"] > current
        ]
        # Re-scan at the same event time. A zero-duration node may release an
        # earlier input-order task, and that dependent must not wait for a later event.
        while True:
            pass_started = False
            for task_id in list(pending):
                task = task_map[task_id]
                if any(dep not in scheduled or scheduled[dep]["finish"] > current for dep in task["depends_on"]):
                    continue
                if task["kind"] == "external" and task["external_ready"] > current:
                    continue
                if task["kind"] == "task":
                    running = active()
                    if plan["max_parallel"] is not None and len(running) >= plan["max_parallel"]:
                        continue
                    held = {resource for active_task in running for resource in active_task["resources"]}
                    if held.intersection(task["resources"]):
                        continue
                start = current
                finish = start + float(task["duration"])
                scheduled[task_id] = {"start": start, "finish": finish}
                pending.remove(task_id)
                pass_started = True
            if not pass_started:
                break
        if pending:
            future = [timing["finish"] for timing in scheduled.values() if timing["finish"] > current]
            for task_id in pending:
                task = task_map[task_id]
                if task["kind"] == "external" and task["external_ready"] is not None and task["external_ready"] > current:
                    future.append(float(task["external_ready"]))
            if not future:
                raise PlanError("内部排程错误：存在无法推进且未标记为阻塞的任务")
            current = min(future)

    output_tasks: list[dict[str, Any]] = []
    for input_index, task in enumerate(tasks):
        result = dict(task)
        result["input_index"] = input_index
        if blocked_by[task["id"]]:
            result.update({
                "status": "blocked",
                "start": None,
                "finish": None,
                "blocked_by": sorted(blocked_by[task["id"]]),
            })
        else:
            result.update({
                "status": "scheduled",
                "start": scheduled[task["id"]]["start"],
                "finish": scheduled[task["id"]]["finish"],
                "blocked_by": [],
            })
        output_tasks.append(result)

    makespan = max((item["finish"] for item in output_tasks if item["finish"] is not None), default=0.0)
    result = {
        "generator": GENERATOR,
        "version": plan["version"],
        "language": plan["language"],
        "title": plan["title"],
        "summary": plan["summary"],
        "unit": plan["unit"],
        "assumptions": plan["assumptions"],
        "risks": plan["risks"],
        "requirements": plan["requirements"],
        "max_parallel": plan["max_parallel"],
        "scheduling": {
            "strategy": "deterministic_topological_list_scheduling",
            "priority": "input_order",
            "dependency_release": "finish",
            "resource_semantics": "exact_string_exclusive_for_task_kind",
            "capacity_semantics": "unbounded_when_null" if plan["max_parallel"] is None else "bounded_task_kind_only",
            "optimality": "heuristic_not_globally_optimal",
            "makespan": makespan,
        },
        "tasks": output_tasks,
    }
    if "localization" in plan:
        result["localization"] = dict(plan["localization"])
        result["_locale_bundle"] = plan["_locale_bundle"]
    return result


def _fmt_time(value: Any) -> str:
    if value is None:
        return "—"
    number = float(value)
    if number.is_integer():
        return f"T+{int(number)}"
    return f"T+{number:.12g}"


def _md(value: Any) -> str:
    text = _clean_text(value)
    for old, new in (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ("\\", "\\\\"),
                     ("|", "\\|"), ("`", "\\`"), ("[", "\\["), ("]", "\\]")):
        text = text.replace(old, new)
    return text.replace("\r\n", "<br>").replace("\n", "<br>").replace("\r", "<br>")


def _list_or_none(items: list[str], messages: dict[str, str]) -> str:
    return messages["list_separator"].join(_md(item) for item in items) if items else _md(messages["none"])


def _clean_text(value: Any) -> str:
    """Replace characters that are invalid in XML/HTML text nodes."""
    return "".join(
        char if char in "\t\n\r" or ord(char) >= 32 else "�"
        for char in str(value)
    )


def _html(value: Any) -> str:
    return html.escape(_clean_text(value), quote=True)


def _ellipsize(value: Any, max_units: int) -> str:
    """Fit mixed CJK/Latin labels into a predictable SVG text budget."""
    text = str(value)
    units = 0
    result: list[str] = []
    for char in text:
        width = 2 if unicodedata.east_asian_width(char) in ("W", "F", "A") else 1
        if units + width > max_units:
            return "".join(result).rstrip() + "…"
        result.append(char)
        units += width
    return text


def render_markdown(schedule: dict[str, Any]) -> str:
    raw_m = _display_messages(schedule)
    m = {key: _md(value) for key, value in raw_m.items()}
    listing = lambda items: m["list_separator"].join(_md(item) for item in items) if items else m["none"]
    capacity = m["capacity_unknown"] if schedule["max_parallel"] is None else str(schedule["max_parallel"])
    lines = [
        f"<!-- {GENERATED_MARKER} -->", "", f"# {m['plan_title']}", "",
        f"**{m['title']}:** {_md(schedule['title'])}", "",
        f"**{m['summary']}:** {_md(schedule['summary'])}", "",
        f"**{m['workload_unit']}:** {_md(schedule['unit'])}", "",
        f"**{m['capacity']}:** {capacity}", "", m["workload_note"], "", m["scheduling_note"],
        "", f"## {m['assumptions']}", "",
    ]
    lines.extend(f"- {_md(item)}" for item in schedule["assumptions"] or [raw_m["none"]])
    lines.extend(["", f"## {m['risks']}", ""])
    lines.extend(f"- {_md(item)}" for item in schedule["risks"] or [raw_m["none"]])
    lines.extend(["", f"## {m['requirement_mapping']}", "",
                  f"| ID | {m['requirement']} | {m['source']} | {m['coverage']} |",
                  "| --- | --- | --- | --- |"])
    for req in schedule["requirements"]:
        covered = [task["id"] for task in schedule["tasks"] if req["id"] in task["requirement_ids"]]
        lines.append(f"| {_md(req['id'])} | {_md(req['text'])} | {_md(req['source'])} | {listing(covered)} |")
    if not schedule["requirements"]:
        lines.append(f"| — | {m['none']} | — | — |")
    lines.extend(["", f"## {m['schedule']}", "",
                  f"| {m['task']} | {m['type']} | {m['start']} | {m['finish']} | {m['workload']} | {m['dependencies']} | {m['resources']} | {m['status']} |",
                  "| --- | --- | ---: | ---: | ---: | --- | --- | --- |"])
    for task in schedule["tasks"]:
        status = m["blocked_reason"].format(items=listing(task["blocked_by"])) if task["status"] == "blocked" else m["scheduled"]
        lines.append(
            f"| {_md(task['id'])} · {_md(task['title'])} | {m['kind_' + task['kind']]} | {_fmt_time(task['start'])} | "
            f"{_fmt_time(task['finish'])} | {_md(task['duration'])} | {listing(task['depends_on'])} | "
            f"{listing(task['resources'])} | {status} |"
        )
    lines.extend(["", f"## {m['task_details']}", ""])
    for task in schedule["tasks"]:
        lines.extend([
            f"### {_md(task['id'])} · {_md(task['title'])}", "", _md(task["description"]) or m["no_description"], "",
            f"- **{m['deliverable']}:** {_md(task['deliverable']) or m['none']}",
            f"- **{m['acceptance']}:** {listing(task['acceptance'])}",
            f"- **{m['pr_scope']}:** {_md(task['pr_scope']) or m['none']}",
            f"- **{m['requirements']}:** {listing(task['requirement_ids'])}",
            f"- **{m['estimate_basis']}:** {_md(task['estimate_basis']) or m['none']}",
            f"- **{m['dependencies']}:** {listing(task['depends_on'])}",
            f"- **{m['resource_locks']}:** {listing(task['resources'])}", "",
        ])
    return "\n".join(lines).rstrip() + "\n"


def _text_units(text: str) -> int:
    return sum(2 if unicodedata.east_asian_width(char) in ("W", "F", "A") else 1 for char in text)


def render_svg(schedule: dict[str, Any], *, standalone: bool = True) -> str:
    m = _display_messages(schedule)
    tasks = schedule["tasks"]
    left, plot_width, right = 300, 760, 270
    width = left + plot_width + right
    row_height = 64
    legend_x, legend_y = 30, 110
    legend = []
    for kind, key, color in (("task", "legend_task", "#2563eb"), ("milestone", "legend_milestone", "#7c3aed"),
                             ("external", "legend_external", "#0d9488"), ("blocked", "legend_blocked", "url(#blocked)")):
        item_width = _text_units(m[key]) * 7 + 48
        if legend_x + item_width > width - 28:
            legend_x, legend_y = 30, legend_y + 26
        if kind == "milestone":
            shape = f'<rect x="{legend_x}" y="{legend_y-7}" width="12" height="12" transform="rotate(45 {legend_x+6} {legend_y-1})" fill="{color}"/>'
