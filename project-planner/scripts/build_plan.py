def _script_json(value: Any) -> str:
    text = json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
    return text.replace('&', '\\u0026').replace('<', '\\u003c').replace('>', '\\u003e').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')


