def _is_ours(path: Path) -> bool:
    if not path.is_file():
        return False
    try:
        if path.name == "schedule.json":
            return json.loads(path.read_text(encoding="utf-8")).get("generator") == GENERATOR
        return GENERATED_MARKER in path.read_text(encoding="utf-8")[:1000]
    except (OSError, UnicodeError, json.JSONDecodeError, AttributeError):
        return False


def write_outputs(input_path: Path, output_dir: Path, schedule: dict[str, Any]) -> None:
    input_real = input_path.resolve()
    output_real = output_dir.resolve()
    if output_real == input_real:
        raise PlanError("输出目录不能与输入文件是同一路径")
    if output_dir.exists() and not output_dir.is_dir():
        raise PlanError(f"输出路径不是目录: {output_dir}")
    targets = {name: output_dir / name for name in OUTPUT_NAMES}
    for target in targets.values():
        if target.resolve() == input_real:
            raise PlanError(f"输入文件与输出产物路径冲突: {target}")
        if target.exists() and not _is_ours(target):
            raise PlanError(f"拒绝覆盖非本生成器产物: {target}")
    contents = {
        "schedule.json": json.dumps(_public_schedule(schedule), ensure_ascii=False, indent=2, allow_nan=False) + "\n",
        "gantt.svg": render_svg(schedule),
        "gantt.html": render_html(schedule),
        "plan.md": render_markdown(schedule),
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in contents.items():
        target = targets[name]
        temp_name = None
        try:
            with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=output_dir, delete=False) as handle:
                handle.write(content)
                temp_name = handle.name
            os.replace(temp_name, target)
        finally:
            if temp_name and os.path.exists(temp_name):
                os.unlink(temp_name)


def run(input_path: Path, output_dir: Path) -> dict[str, Any]:
    try:
        raw = json.loads(input_path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise PlanError(f"找不到输入文件: {input_path}") from exc
    except UnicodeDecodeError as exc:
        raise PlanError(f"输入文件必须是 UTF-8: {input_path}") from exc
    except json.JSONDecodeError as exc:
        raise PlanError(f"JSON 解析失败（第 {exc.lineno} 行，第 {exc.colno} 列）: {exc.msg}") from exc
    schedule = build_schedule(validate_plan(raw, input_dir=input_path.resolve().parent))
    write_outputs(input_path, output_dir, schedule)
    return schedule


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="校验项目计划并生成离线排程、甘特图和 Markdown。")
    parser.add_argument("input", type=Path, help="UTF-8 JSON 计划文件")
    parser.add_argument("--output", type=Path, required=True, help="输出目录")
    args = parser.parse_args(argv)
    try:
        schedule = run(args.input, args.output)
    except (PlanError, OSError) as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 2
    blocked = sum(task["status"] == "blocked" for task in schedule["tasks"])
    print(f"已生成 {len(OUTPUT_NAMES)} 个产物到 {args.output}；任务 {len(schedule['tasks'])}，阻塞 {blocked}。")
    return 0


